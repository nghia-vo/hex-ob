# `controller.create_block("modules/pcap/pcap.block.ini", 1, 8)`
_CREATE_BLOCK_RE = re.compile(
    r"""create_block\(\s*["']([^"']+)["']\s*,\s*(\d+)\s*,\s*(\d+)\s*\)"""
)


def load_blocks():
    """Return the (ini_path, number, address) block list for the sim.

    Prefer the create_block() calls in the original generated sim_server so the
    simulated block set always matches config_d; fall back to a static list.
    Unsupported (FPGA-only) blocks are dropped either way.
    """
    orig = os.path.join(os.path.dirname(__file__), "sim_server.orig")
    blocks = []
    try:
        with open(orig) as f:
            for ini_path, number, address in _CREATE_BLOCK_RE.findall(f.read()):
                blocks.append((ini_path, int(number), int(address)))
    except OSError:
        blocks = []
    if not blocks:
        blocks = list(FALLBACK_BLOCKS)
    return [
        b
        for b in blocks
        if os.path.basename(b[0]).replace(".block.ini", "") not in UNSUPPORTED_BLOCKS
    ]


def configure_pcap_registers(controller, config_dir):
    """Point the *REG PCAP registers at the sim, using the real offsets.

    Two things are wrong out of the box for a real app config:

    1. ``SimulationController`` hardcodes the *REG PCAP register offsets
       (START_WRITE=8, WRITE=9, ARM=10, DISARM=11). That is only correct for the
       engine's default layout. The ``pandabox-no-fmc`` app inserts optional
       ``PCAP_TS_SEC``/``PCAP_TS_TICKS`` registers, shifting ARM/DISARM to 13/14
       in the generated ``registers`` file the C server actually uses. So a real
       ``*PCAP.ARM=`` writes register 13, which the sim leaves unmapped -> the
       arm is silently dropped and ``PCAP.ACTIVE`` never latches.
    2. The mapped names are prefixed (``PCAP_ARM``), but ``pcap_sim.on_changes``
       only acts on the bare names (``ARM``/``DISARM``/``START_WRITE``/``WRITE``).

    Re-derive the offsets from ``config_d/registers`` and map them to the bare
    names the simulation acts on.
    """
    pcap = getattr(controller, "pcap", None)
    if pcap is None:
        return
    # Drop the engine's hardcoded (and here incorrect) *REG PCAP offsets.
    for key in list(controller.lookup):
        block, name = controller.lookup[key]
        if block is pcap and key[0] == 0 and isinstance(name, str) \
                and name.startswith("PCAP_"):
            del controller.lookup[key]
    wanted = {
        "PCAP_START_WRITE": "START_WRITE",
        "PCAP_WRITE": "WRITE",
        "PCAP_ARM": "ARM",
        "PCAP_DISARM": "DISARM",
    }
    regfile = os.path.join(config_dir, "registers")
    with open(regfile) as f:
        for line in f:
            toks = line.split()
            # Lines look like: "PCAP_ARM 13" or "PCAP_TS_SEC opt 10"
            if len(toks) >= 2 and toks[0] in wanted:
                try:
                    offset = int(toks[-1])
                except ValueError:
                    continue
                controller.lookup[(0, 0, offset)] = (pcap, wanted[toks[0]])


def install_signed_writes(controller, blocks):
    """Sign-extend register writes to fields the block inis declare signed.

    The C server transports every register write as a raw uint32, but the
    Python engine computes in arbitrary-precision ints. A field the app
    declares ``param int`` (PCOMP START/STEP/WIDTH/PRE_START, ...) written
    as e.g. -39460 therefore arrives as 4294927836, and PCOMP's
    ``posn() >= next_crossing`` can never be true: a fly scan over the real
    encoder range (offset -39660) waits forever in WAIT_RISING while the
    positive-range smoke test passes. Wrap ``do_write_register`` to fold
    values back into int32 range for exactly the fields whose ini type
    carries the ``int`` (signed) token.
    """
    signed_by_addr = {}
    for ini_path, _num, addr in blocks:
        cp = configparser.ConfigParser(strict=False, interpolation=None)
        cp.read(os.path.join(_FPGA_ROOT, ini_path))
        fields = set()
        for section in cp.sections():
            if "int" in cp[section].get("type", "").split():
                fields.add(section.upper())
        if fields:
            signed_by_addr[addr] = fields
    signed = set()
    for (addr, _inum, _reg), (block, field) in controller.lookup.items():
        if isinstance(field, str) and \
                field.upper() in signed_by_addr.get(addr, ()):
            signed.add((block, field))

    orig_write = controller.do_write_register

    def do_write_register(block_num, num, reg, value):
        entry = controller.lookup.get((block_num, num, reg))
        if entry and (entry[0], entry[1]) in signed and value >= 0x80000000:
            value -= 0x100000000
        return orig_write(block_num, num, reg, value)

    controller.do_write_register = do_write_register


def build_block_index(controller, blocks):
    """Map PandA block names (e.g. ``INENC1``) to their simulation instances.

    Used by the position-injection channel to resolve a ``<BLOCK> <FIELD>``
    target to the block instance whose field is driven. PandA numbers blocks
    from 1 (``INENC1`` == instance 0), matching the control protocol.
    """
    addr_name = {addr: os.path.basename(ini).replace(".block.ini", "").upper()
                 for ini, _num, addr in blocks}
    index = {}
    for (addr, inum, _reg), (block, _field) in controller.lookup.items():
        if isinstance(block, SimulationController) or addr not in addr_name:
            continue
        index["%s%d" % (addr_name[addr], inum + 1)] = block
    return index


class SocketFail(Exception):
    pass


class Py3SimulationServer:
    """Register-protocol socket server (Python-3 clean).

    Speaks the same 4-byte command protocol as PandABlocks-FPGA's
    `SimulationServer`, delegating all logic to the shared
    `SimulationController` engine.
    """

    def __init__(self, controller, host="localhost", port=9999,
                 inject_port=0, block_index=None):
        self.controller = controller
        self.block_index = block_index or {}
        self.sock_l = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.sock_l.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.sock_l.bind((host, port))
        self.sock_l.listen(0)
        self.sock = None
        # Optional position-injection channel (a bridge feeds the moving motor
        # position into the sim's encoder input so PCOMP/PULSE/PCAP capture).
        self.inject_l = None
        self.inject_clients = []
        self._inject_buf = {}
        if inject_port:
            self.inject_l = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            self.inject_l.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            self.inject_l.bind((host, inject_port))
            self.inject_l.listen(4)

    def run(self):
        (self.sock, _addr) = self.sock_l.accept()
        self.sock_l.close()
        self.sock.setsockopt(socket.SOL_TCP, socket.TCP_NODELAY, 1)
        try:
            while True:
                timeout = self.controller.calc_timeout()
                readers = [self.sock]
                if self.inject_l is not None:
                    readers.append(self.inject_l)
                readers.extend(self.inject_clients)
                rlist, _, _ = select.select(readers, (), (), timeout)
                if self.sock in rlist:
                    self._respond()
                if self.inject_l is not None and self.inject_l in rlist:
                    self._accept_inject()
                for client in list(self.inject_clients):
                    if client in rlist:
                        self._handle_inject(client)
                self.controller.do_tick()
        except (KeyboardInterrupt, SocketFail) as e:
            print("Simulation closed: %r" % e)

    def _accept_inject(self):
        client, _addr = self.inject_l.accept()
        client.setsockopt(socket.SOL_TCP, socket.TCP_NODELAY, 1)
        # Non-blocking: a client that stops reading its replies must never
        # stall the engine loop (a blocked sendall here froze the whole sim
        # once the peer's receive buffer filled).
        client.setblocking(False)
        self.inject_clients.append(client)
        self._inject_buf[client] = b""

    def _handle_inject(self, client):
        try:
            chunk = client.recv(4096)
        except (BlockingIOError, InterruptedError):
            return
        except OSError:
            chunk = b""
        if not chunk:
            self.inject_clients.remove(client)
            self._inject_buf.pop(client, None)
            client.close()
            return
        buf = self._inject_buf[client] + chunk
        lines = buf.split(b"\n")
        self._inject_buf[client] = lines.pop()
        for line in lines:
            reply = self._apply_inject(line.decode("ascii", "replace").strip())
            # Replies are best-effort acknowledgements: drop them rather than
            # ever blocking the engine on a peer that is not reading.
            try:
                client.send((reply + "\n").encode())
            except OSError:
                pass

    def _apply_inject(self, line):
        """Apply one ``<BLOCK> <FIELD> <int>`` injection line to the engine."""
        if not line or line.startswith("#"):
            return "OK"
        parts = line.split()
        if len(parts) != 3:
            return "ERR expected '<BLOCK> <FIELD> <int>'"
        name, field, raw = parts
        block = self.block_index.get(name.upper())
        if block is None:
            return "ERR unknown block %s" % name
        try:
            value = int(float(raw))
        except ValueError:
            return "ERR bad value %s" % raw
        # Drive the field as if the block produced it; the engine fans the
        # change out to listeners (CALC/PCOMP) and schedules PCAP.
        self.controller.do_tick({block: {field.upper(): value}})
        return "OK"

    def _read(self, n):
        result = b""
        while len(result) < n:
            rx = self.sock.recv(n - len(result))
            if not rx:
                raise SocketFail("End of input")
            result += rx
        return result

    def _respond(self):
        command_word = self._read(4)
        command, block, num, reg = struct.unpack("cBBB", command_word)
        if command == b"R":
            tx = self.controller.do_read_register(block, num, reg)
            self.sock.sendall(struct.pack("I", tx & 0xFFFFFFFF))
        elif command == b"W":
            (value,) = struct.unpack("I", self._read(4))
            self.controller.do_write_register(block, num, reg, value)
        elif command == b"T":
            (length,) = struct.unpack("I", self._read(4))
            data = self._read(length * 4)
            data = np.frombuffer(data, dtype=np.int32)
            self.controller.do_write_table(block, num, data)
        elif command == b"D":
            (length,) = struct.unpack("I", self._read(4))
            data = self.controller.do_read_capture(length // 4)
            if data is None:
                self.sock.sendall(struct.pack("i", -1))
            else:
                raw = np.ascontiguousarray(data, dtype="<i4").tobytes()
                assert len(raw) <= length
                self.sock.sendall(struct.pack("I", len(raw)))
                self.sock.sendall(raw)
        else:
            raise SocketFail("Unexpected command %r" % command_word)


def main():
    parser = argparse.ArgumentParser(description="PandA Py3 hardware simulation")
    parser.add_argument(
        "-d", "--daemon", action="store_true", help="Run as daemon process"
    )
    parser.add_argument(
        "-v", "--verbose", action="store_true", help="Log register access"
    )
    args = parser.parse_args()

    controller = SimulationController(args.verbose)
    block_list = load_blocks()
    for ini_path, number, block_address in block_list:
        controller.create_block(ini_path, number, block_address)

    config_dir = os.environ.get("PANDA_CONFIG_D") or os.path.join(
        os.path.dirname(__file__), "config_d"
    )
    configure_pcap_registers(controller, config_dir)
    install_signed_writes(controller, block_list)
    block_index = build_block_index(controller, block_list)

    # Position-injection channel (default 9101). A host-side bridge feeds the
    # moving motor position into the encoder input so the capture chain fires.
    inject_port = int(os.environ.get("PANDA_INJECT_PORT", "9101"))

    # Bind the socket BEFORE daemonising so the C server can connect to the
    # inherited listening socket once the launcher returns.
    server = Py3SimulationServer(
        controller, inject_port=inject_port, block_index=block_index
    )

    print("Simulating server ready")
    sys.stdout.flush()
    if args.daemon:
        daemonise()
    server.run()


if __name__ == "__main__":
    main()
