#!/usr/bin/env python3
# Python-3 PandA hardware-simulation daemon for the HEX sim (Option C).
#
# Background
# ----------
# The PandABlocks-server `simserver` normally launches its *bundled* register
# simulator (`server/python/sim_server`), which is "as dumb as a brick": it
# implements the register read/write protocol but runs NO block timing logic.
# That is why CLOCK/PCOMP/PULSE/PCAP never tick and PCAP:ACTIVE never latches,
# so an ophyd-async fly scan (arm -> wait pcap.active -> capture) stalls.
#
# PandABlocks-FPGA ships a *real* cycle-accurate block-simulation engine in
# `common/python/simulations.py` (SimulationController + per-block `*_sim.py`
# models). Its `generate_app` step also emits an autogenerated `sim_server`
# that wires the engine up to the register socket the C server talks to -- but
# that generated script is Python 2 (`print` statements) and the socket layer
# in `simulations.py` still uses Python-2 byte handling, so it will not run
# under the container's `python3`.
#
# This wrapper reuses the (Python-3 clean) `SimulationController` engine and
# per-block models unchanged, and reimplements ONLY the thin register socket
# loop in correct Python 3. It is dropped in as `<dir>/autogen/sim_server` and
# selected via `simserver -f <dir>`.
#
# Block list mirrors the autogen sim_server for the `pandabox-no-fmc` app,
# minus the two `sfp_panda_sync` blocks: those require FPGA pin-constraint
# metadata (`site_LOC`) that is absent for a soft build, and they are unused by
# tomography fly scans. Register reads to their (dropped) addresses fall through
# to the controller's graceful default of 0.

