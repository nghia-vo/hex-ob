# The engine schedules wakeups as (ts, block, changes) tuples and inserts them
# with bisect. When two wakeups share a timestamp -- which happens as soon as a
# position change fans out to more than one listener (e.g. INENC.VAL -> both
# PCOMP.INP and PCAP) -- bisect tries to order the block instances and raises
# TypeError (blocks aren't comparable). The block-timing tests never hit this
# (they drive a single block in isolation). Give blocks a stable id-based order
# so equal-timestamp wakeups sort deterministically without touching the engine.
BlockSimulation.__lt__ = lambda self, other: id(self) < id(other)


# ---- Engine wakeup-merge patches -------------------------------------------
# The stock engine LOSES pending wakeup changes whenever two changes collide on
# one block, in three places:
#
#   1. `do_tick` schedule loop: a listener block with a queued wakeup that
#      carries changes (e.g. PCOMP holding ENABLE=1 fanned out from a BITS.A
#      write) has that wakeup removed and replaced when a new change arrives
#      (e.g. INP from a position injection) -- the queued ENABLE is dropped, so
#      PCOMP/PULSE/PCAP silently never enable. With a bridge injecting
#      positions continuously this is not a race but a certainty.
#   2. `do_tick` due-wakeup loop: `block_changes.setdefault(...)` discards the
#      due wakeup's changes if the same block also has direct changes this tick.
#   3. `process_blocks`: a block receiving direct changes has its pending
#      wakeup dropped via `remove_wakeup`.
#
# `remove_wakeup` itself is also unusable here: it bisects with a
# (ts, None, None) probe that raises TypeError comparing None against a block
# whenever timestamps collide, and asserts the popped wakeup carries no
# changes. The replacements below MERGE colliding changes (newest value wins
# per field, nothing is dropped) and pop pending wakeups with a linear scan
# (the list holds at most one entry per block).


def _pop_pending_wakeup(controller, block):
    """Remove ``block``'s queued wakeup and return the changes it carried."""
    old_ts = controller.next_wakeup.pop(block, None)
    if old_ts is None:
        return None
    for i, (_w_ts, w_block, w_changes) in enumerate(controller.wakeups):
        if w_block is block:
            controller.wakeups.pop(i)
            return w_changes
    return None


def _merging_do_tick(self, block_changes=None):
    ts = int((time.time() - self.start_time) / CLOCK_TICK)
    if block_changes is None:
        block_changes = {}
    # If we have a wakeup, then make sure we aren't going back in time
    if self.wakeups:
        wake_ts, _, _ = self.wakeups[0]
        if ts > wake_ts:
            ts = wake_ts
    # Merge every wakeup due at this ts into block_changes (never drop either)
    while self.wakeups and self.wakeups[0][0] == ts:
        _w_ts, wake_block, wake_changes = self.wakeups.pop(0)
        self.next_wakeup[wake_block] = None
        if wake_block in block_changes:
            merged = dict(wake_changes)
            merged.update(block_changes[wake_block])
            block_changes[wake_block] = merged
        else:
            block_changes[wake_block] = wake_changes
    new_wakeups = self.process_blocks(ts, block_changes)
    # Re-schedule, folding any still-queued changes into the new wakeup
    for (block, wakeup), changes in new_wakeups.items():
        pending = _pop_pending_wakeup(self, block)
        if pending:
            merged = dict(pending)
            merged.update(changes)
            changes = merged
        self.insert_wakeup(wakeup, block, changes)


def _merging_process_blocks(self, ts, block_changes):
    # map block -> changes
    new_wakeups = {}
    pos_changes = []
    for block, changes in block_changes.items():
        # Fold the block's queued-but-not-yet-delivered changes in ahead of
        # the new ones instead of discarding them with its wakeup.
        pending = _pop_pending_wakeup(self, block)
        if pending:
            merged = dict(pending)
            merged.update(changes)
            changes = merged
        next_ts = block.on_changes(ts, changes)
        # PULSE-train fix: pulse_sim tracks its next edge in `edge_ts` but its
        # on_changes only ever returns queue-head times, never edge_ts — on
        # real FPGA every clock processes, but this event-driven server only
        # calls a block at its returned wakeup, so a started train emits its
        # first edge and then dies. Duck-typed on purpose: any block modelling
        # a pending edge this way gets woken for it.
        if getattr(block, "edges_remaining", 0):
            edge_ts = getattr(block, "edge_ts", None)
            if edge_ts is not None and edge_ts > ts and \
                    (next_ts is None or edge_ts < next_ts):
                next_ts = edge_ts
        # Update bit_bus and pos_bus
        for attr, val in block.changes.items():
            data = self.bus_lookup.get((block, attr), None)
            if data is None:
                continue
            bus, bus_changes, idx = data
            if bus is BlockSimulation.pos_bus:
                pos_changes.append(idx)
            bus[idx] = val
            bus_changes[idx] = 1
            # If someone's listening, tell them about it
            for lblock, lattr in self.listeners.get((block, attr), []):
                dly = self.delays.get((lblock, lattr), 0)
                new_wakeups.setdefault((lblock, ts + 1 + dly), {})[lattr] = val
        # Reset the changed attributes dict
        block.changes = {}
        # If we are due to be woken up, add this one to the wakeup dict
        if next_ts is not None:
            new_wakeups.setdefault((block, next_ts), {})
    if pos_changes:
        new_wakeups.setdefault((self.pcap, ts + 1), {})["POS_BUS"] = \
            pos_changes
    return new_wakeups


SimulationController.do_tick = _merging_do_tick
SimulationController.process_blocks = _merging_process_blocks

